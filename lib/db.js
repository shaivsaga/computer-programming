import pg from "pg";

const SCHEMA = `
  SELECT pg_advisory_xact_lock(104, 1);

  CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS sessions (
    id         CHAR(64) PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);
  CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
`;

let connectionPool;
let schemaReady;

export async function query(sql, values) {
  if (!connectionPool) {
    const connectionString = process.env.DATABASE_URL;
    if (!connectionString) throw new Error("DATABASE_URL is required.");

    connectionPool = new pg.Pool({
      connectionString,
      max: 5,
      connectionTimeoutMillis: 5000,
    });
    connectionPool.on("error", (error) => {
      console.error("Idle database connection failed:", error.code);
    });
  }

  // PostgreSQL runs this batch in one transaction. The lock prevents cold
  // starts from racing to create the same tables and indexes.
  schemaReady ??= connectionPool.query(SCHEMA).catch((error) => {
    schemaReady = undefined;
    throw error;
  });
  await schemaReady;

  return connectionPool.query(sql, values);
}
